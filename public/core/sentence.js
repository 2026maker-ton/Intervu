// 답변 마무리 판단: 전사 끝이 한국어 종결어미(…다/…요/…죠/…까)로 끝났는지. 문장부호·따옴표·공백은 무시한다.
// 면접실은 발화 뒤 3초 정적으로 끊긴 구간을 전사한 다음 이 판단이 참이면 답변을 넘긴다(AI 호출 없음).
// ponytail: 어미 규칙이라 "그리고 다음은…다" 같은 중간 문장도 끝으로 볼 수 있다. 오판이 많으면 어미 목록을 좁힌다.
export const endsSentence = (text) => /[가-힣]{1,}(다|요|죠|까)[\s.?!。…~"'”’)]*$/.test(String(text || '').trim());
