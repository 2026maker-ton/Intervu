test('C5 benign corpus (>=60): name/school/address/id_number 탐지 0건, 마스킹 불변', () => {
  assert.ok(BENIGN.length >= 60);
  for (const t of BENIGN) {
    assert.deepEqual(newHits(t), [], t);
    assert.equal(maskPii(t), t, t);
  }
});

test('C5 positive corpus (>=30): 해당 타입 탐지 + 마스킹 시 값 제거', () => {
  assert.ok(POSITIVE.length >= 30);
  for (const [t, type] of POSITIVE) {
    const hits = newHits(t).filter((h) => h.type === type);
    assert.ok(hits.length > 0, `${type}: ${t}`);
    const masked = maskPii(t);
    for (const h of hits) assert.ok(!masked.includes(h.value), `masked: ${t} -> ${masked}`);
  }
});

test('C5 기존 타입 호환: email/phone/rrn 입력은 기존 타입만 보고', () => {
  const t = '연락처 010-1234-5678, a@b.com, 900101-1234567';
  assert.deepEqual(detectPii(t).map((h) => h.type).sort(), ['email', 'phone', 'rrn']);
});

test('C5 maskPii 멱등 + 일반 키워드 보존(길이 비의존)', () => {
  const t = '제 이름은 김철수입니다. 서울시 강남구 테헤란로 123 에 삽니다. 협업 경험이 있습니다.';
  const m = maskPii(t);
  assert.equal(maskPii(m), m);
  assert.ok(m.includes('협업'));
});
